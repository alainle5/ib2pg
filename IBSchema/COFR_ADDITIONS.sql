create procedure cofr_additions (
    ipolicyid integer,
    ibatchno  integer)
as
 BEGIN

  /* All vessels which are configured for COFR, do not have archived versions, and are not already in the queue */
  INSERT INTO PRINT_QUEUE (QUEUE_ID, QUEUE_SECTION, QUEUE_TYPE, POLICY_ID, BATCH_NO, ORIGIN_ID, QUEUE_DATE, PRINTED_DATE)
  SELECT
    GEN_ID(QUEUE_ID_GEN, 1), "COFR", "ADDED", V.POLICY_ID, V.BATCH_NO, V.ORIGIN_ID, "NOW", NULL
  FROM
    VESSELS V
  WHERE
    V.POLICY_ID = :iPolicyID AND
    V.BATCH_NO = :iBatchNo AND
    V.COFR = 1 AND
    V.STATUS IN ("", "H") AND
    NOT EXISTS( SELECT O.UNIQUE_ID FROM VESSELS O WHERE O.POLICY_ID = V.POLICY_ID AND O.ITEM_NO = V.ITEM_NO AND O.BATCH_NO < V.BATCH_NO ) AND
    NOT EXISTS( SELECT Q.QUEUE_ID FROM PRINT_QUEUE Q WHERE Q.POLICY_ID = V.POLICY_ID AND Q.BATCH_NO = V.BATCH_NO AND Q.ORIGIN_ID = V.ORIGIN_ID AND Q.PRINTED_DATE IS NULL);
  
  
  /* All vessels which are configured for COFR, have an archived version which was _not_ configured for COFR, and are not in the queue */
  INSERT INTO PRINT_QUEUE (QUEUE_ID, QUEUE_SECTION, QUEUE_TYPE, POLICY_ID, BATCH_NO, ORIGIN_ID, QUEUE_DATE, PRINTED_DATE)
  SELECT
    GEN_ID(QUEUE_ID_GEN, 1), "COFR", "ADDED", V.POLICY_ID, V.BATCH_NO, V.ORIGIN_ID, "NOW", NULL
  FROM
    VESSELS V,
    VESSELS O
  WHERE
    V.POLICY_ID = :iPolicyID AND
    V.BATCH_NO = :iBatchNo AND
    V.COFR = 1 AND
    V.STATUS IN ("", "H") AND
    O.POLICY_ID = V.POLICY_ID AND
    O.ITEM_NO = V.ITEM_NO AND
    O.COFR = 0 AND
    O.STATUS IN ("", "H") AND
    O.BATCH_NO = ( SELECT MAX(B.BATCH_NO) FROM VESSELS B WHERE B.POLICY_ID = V.POLICY_ID AND B.ITEM_NO = V.ITEM_NO AND B.BATCH_NO < V.BATCH_NO ) AND
    NOT EXISTS( SELECT Q.QUEUE_ID FROM PRINT_QUEUE Q WHERE Q.POLICY_ID = V.POLICY_ID AND Q.BATCH_NO = V.BATCH_NO AND Q.ORIGIN_ID = V.ORIGIN_ID AND Q.PRINTED_DATE IS NULL );
  
END